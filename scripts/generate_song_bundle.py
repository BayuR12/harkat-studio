# 3. Create MIDI file using a standard binary MIDI generator
def create_midi_file(filepath):
    # Standard MIDI Header: 'MThd', 6 bytes, format 0 (single track), 1 track, 480 ticks/quarter
    header = b'MThd' + (6).to_bytes(4, 'big') + (0).to_bytes(2, 'big') + (1).to_bytes(2, 'big') + (480).to_bytes(2, 'big')
    
    # Track events: Tempo 96 BPM (625,000 micros/quarter note)
    # Set Tempo meta event: delta 0, FF 51 03, 09 89 68
    events = bytearray()
    events += b'\x00\xFF\x51\x03\x09\x89\x68'
    
    # Track name: "Yang Pergi Kamu"
    track_name = "Yang Pergi Kamu, Bukan Hidupku".encode('utf-8')
    events += b'\x00\xFF\x03' + bytes([len(track_name)]) + track_name
    
    # Chord notes: Am (A3, C4, E4), G (G3, B3, D4), F (F3, A3, C4), E (E3, G#3, B3)
    chords = [
        ([57, 60, 64], 1920),  # Am, 4 beats
        ([55, 59, 62], 1920),  # G, 4 beats
        ([53, 57, 60], 1920),  # F, 4 beats
        ([52, 56, 59], 1920),  # E, 4 beats
        ([53, 57, 60], 1920),  # Chorus F
        ([55, 59, 62], 1920),  # Chorus G
        ([57, 60, 64], 3840),  # Chorus Am (2 bars)
    ]
    
    def write_varlen(val):
        buf = []
        buf.append(val & 0x7F)
        val >>= 7
        while val > 0:
            buf.append((val & 0x7F) | 0x80)
            val >>= 7
        buf.reverse()
        return bytes(buf)

    for chord, duration in chords:
        # Note on events for each note in chord
        for i, note in enumerate(chord):
            events += write_varlen(0)
            events += bytes([0x90, note, 90])  # Channel 0, Note, Vel 90
            
        # Note off event for the first note after duration ticks
        events += write_varlen(duration)
        events += bytes([0x80, chord[0], 0])
        # Note off for remaining notes at delta 0
        for note in chord[1:]:
            events += write_varlen(0)
            events += bytes([0x80, note, 0])
            
    # End of track meta event
    events += b'\x00\xFF\x2F\x00'
    
    track_chunk = b'MTrk' + len(events).to_bytes(4, 'big') + bytes(events)
    with open(filepath, 'wb') as f:
        f.write(header + track_chunk)
    print(f"Created {filepath}")

midi_path = os.path.join(OUTPUT_DIR, 'yang-pergi-kamu.mid')
create_midi_file(midi_path)

